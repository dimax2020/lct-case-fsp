@dataclass(frozen=True)
class CheckItem:
    id: str
    text: str


@dataclass(frozen=True)
class ConcreteQ:
    question: str
    needles: tuple[str, ...]


@dataclass(frozen=True)
class Probe:
    id: str
    specialization: str
    title: str
    prompt: str
    levels: dict[str, tuple[CheckItem, ...]]
    concrete: dict[str, ConcreteQ]


def _checks(prefix: str, lines: tuple[str, ...]) -> tuple[CheckItem, ...]:
    return tuple(CheckItem(id=f"{prefix}-{index}", text=line) for index, line in enumerate(lines, start=1))


def _probe(
    probe_id: str,
    specialization: str,
    title: str,
    prompt: str,
    junior: tuple[str, ...],
    middle: tuple[str, ...],
    senior: tuple[str, ...],
    questions: dict[str, tuple[str, tuple[str, ...]]],
) -> Probe:
    return Probe(
        id=probe_id,
        specialization=specialization,
        title=title,
        prompt=prompt,
        levels={
            "junior": _checks(f"{probe_id}-j", junior),
            "middle": _checks(f"{probe_id}-m", middle),
            "senior": _checks(f"{probe_id}-s", senior),
        },
        concrete={
            level: ConcreteQ(question=question, needles=needles)
            for level, (question, needles) in questions.items()
        },
    )


