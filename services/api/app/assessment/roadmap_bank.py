def probes_for(specialization: str) -> tuple[Probe, ...]:
    return tuple(item for item in PROBES if item.specialization == specialization)


LABELS = {
    "be-http": "HTTP",
    "be-sql": "Базы",
    "be-auth": "Доступ",
    "be-scale": "Нагрузка",
    "fe-html": "HTML",
    "fe-css": "Вёрстка",
    "fe-js": "JavaScript",
    "fe-perf": "Браузер",
}


def map_label(probe: Probe) -> str:
    return LABELS.get(probe.id, probe.title)


def probe_by_id(probe_id: str) -> Probe | None:
    for item in PROBES:
        if item.id == probe_id:
            return item
    return None


def choose_probe_ids(specialization: str, seed: str, count: int = PROBES_PER_RUN) -> list[str]:
    items = [item.id for item in probes_for(specialization)]
    if len(items) < count:
        raise ValueError(specialization)
    ranked = sorted(items, key=lambda item: hashlib.sha256(f"{seed}:{item}".encode()).hexdigest())
    return ranked[:count]
